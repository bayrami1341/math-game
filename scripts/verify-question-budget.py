GRAND_TOTAL = (456, 684)
GRAND_LEVELS = {"دانشی": (150, 226), "کاربردی": (212, 318), "استدلالی": (94, 140)}
LEVELS = ["دانشی", "کاربردی", "استدلالی"]
FA = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def fa(n: int) -> str:
    return str(n).translate(FA)


def main() -> int:
    errs = []

    # ۱) خودسازگاری ردیف‌های فرعی
    for ch, title, d, a, s, tot in SUBS:
        if d[0] + a[0] + s[0] != tot[0]:
            errs.append(f"ردیف فرعی ف{ch} «{title}»: جمع حداقل سطح‌ها {d[0]+a[0]+s[0]} ≠ {tot[0]}")
        if d[1] + a[1] + s[1] != tot[1]:
            errs.append(f"ردیف فرعی ف{ch} «{title}»: جمع حداکثر سطح‌ها {d[1]+a[1]+s[1]} ≠ {tot[1]}")
    print(f"۱) خودسازگاری {fa(len(SUBS))} ردیف فرعی (سه سطح = جمع ردیف): " + ("✅" if not errs else "❌"))

    # ۲) جمع فرعی‌های هر فصل = ردیف اصلی
    by_ch = {}
    for ch, t, d, a, s, tot in SUBS:
        by_ch.setdefault(ch, []).append((d, a, s, tot))
    n2 = 0
    for ch, (title, mn, mx, D, A, S) in MAIN.items():
        rows = by_ch.get(ch, [])
        smn, smx = sum(r[3][0] for r in rows), sum(r[3][1] for r in rows)
        if (smn, smx) != (mn, mx):
            errs.append(f"ف{ch} «{title}»: جمع فرعی‌ها {smn}–{smx} ≠ جدول اصلی {mn}–{mx}")
        for idx, lv in enumerate((D, A, S)):
            lmn, lmx = sum(r[idx][0] for r in rows), sum(r[idx][1] for r in rows)
            if (lmn, lmx) != lv:
                errs.append(f"ف{ch} سطح {LEVELS[idx]}: جمع فرعی‌ها {lmn}–{lmx} ≠ {lv[0]}–{lv[1]}")
        n2 += 1
    print(f"۲) جمع ردیف‌های فرعی هر فصل = ردیف فصل در جدول اصلی ({fa(n2)} فصل × جمع + ۳ سطح): " + ("✅" if not errs else "❌"))

    # ۳) جمع‌های کل
    gmn, gmx = sum(v[1] for v in MAIN.values()), sum(v[2] for v in MAIN.values())
    if (gmn, gmx) != GRAND_TOTAL:
        errs.append(f"جمع کل: {gmn}–{gmx} ≠ {GRAND_TOTAL[0]}–{GRAND_TOTAL[1]}")
    for name, glv in GRAND_LEVELS.items():
        li = 3 + ["دانشی", "کاربردی", "استدلالی"].index(name)
        lmn, lmx = sum(v[li][0] for v in MAIN.values()), sum(v[li][1] for v in MAIN.values())
        if (lmn, lmx) != glv:
            errs.append(f"جمع کل {name}: {lmn}–{lmx} ≠ {glv[0]}–{glv[1]}")
    print(f"۳) جمع‌های کل — {fa(gmn)} تا {fa(gmx)} سؤال + سه سطح کل: " + ("✅" if not errs else "❌"))

    # ۴) نسبت میانهٔ سه سطح
    mid = {k: (g[0] + g[1]) / 2 for k, g in [("d", GRAND_LEVELS["دانشی"]), ("a", GRAND_LEVELS["کاربردی"]), ("s", GRAND_LEVELS["استدلالی"])]}
    mid["t"] = (GRAND_TOTAL[0] + GRAND_TOTAL[1]) / 2
    pd, pa, ps = mid["d"] / mid["t"] * 100, mid["a"] / mid["t"] * 100, mid["s"] / mid["t"] * 100
    within = abs(pd - 33) <= 1 and abs(pa - 46) <= 1 and abs(ps - 21) <= 1
    print(f"۴) نسبت میانهٔ سه سطح: دانشی {pd:.1f}٪ / کاربردی {pa:.1f}٪ / استدلالی {ps:.1f}٪ — ادعای مالک ۳۳/۴۶/۲۱: " + ("✅" if within else "❌"))
    if not within:
        errs.append("نسبت سه سطح با ادعای مالک بیش از ۱٪ فاصله دارد")

    print("\nنتیجه: " + ("هر دو جدول بودجه کاملاً سازگارند — گیت سبز ✅" if not errs else "ناسازگاری — گیت قرمز ❌"))
    for e in errs:
        print("  ❌ " + e)
    return 0 if not errs else 1


