wb = Workbook()

def new_sheet(title, widths):
    ws = wb.create_sheet(title)
    ws.sheet_view.rightToLeft = True
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    return ws

def title_row(ws, text, ncols, row=1):
    ws.cell(row=row, column=1, value=text).font = TITLE_FONT
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    ws.row_dimensions[row].height = 26

def header(ws, row, headers):
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=row, column=c, value=h)
        cell.fill, cell.font, cell.alignment, cell.border = HDR_FILL, HDR_FONT, CENTER, THIN
    ws.row_dimensions[row].height = 30
    ws.freeze_panes = ws.cell(row=row+1, column=1).coordinate

def put(ws, row, values, fill=None, font=None):
    for c, v in enumerate(values, 1):
        cell = ws.cell(row=row, column=c, value=v)
        cell.font = font or BODY_FONT
        cell.alignment = WRAP_RIGHT
        cell.border = THIN
        if fill: cell.fill = fill

